// Keep the public language reference in step with the choices the apps actually offer.
const fs = require('node:fs');
const path = require('node:path');
const schema = require('../core/schema');
const { ENGINES, TARGETS } = require('../server/lib/jobs');

const display = (label) => label.replace(/繁體中文/g, '繁体中文');
const entries = (codes, names) => codes.map((code) => ({ code, label: display(names[code]) }));
const data = {
  liveInput: entries(schema.SPLIT_SOURCES, schema.LANG_NAMES),
  liveOutput: entries(schema.SPLIT_TARGETS, schema.LANG_NAMES),
  fileInput: entries(Object.keys(ENGINES), Object.fromEntries(Object.entries(ENGINES).map(([code, engine]) => [code, engine.label]))),
  fileOutput: entries(Object.keys(TARGETS).filter((code) => code !== 'none'), TARGETS),
};
const output = `// Generated by web/generate-site-languages.js from core/schema.js and server/lib/jobs.js.\n` +
  `globalThis.SITE_LANGUAGES = ${JSON.stringify(data, null, 2)};\n` +
  `if (typeof module !== 'undefined') module.exports = globalThis.SITE_LANGUAGES;\n`;
const target = path.join(__dirname, 'site-languages.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('Public language reference is out of date. Run node web/generate-site-languages.js.');
    process.exitCode = 1;
  }
} else fs.writeFileSync(target, output);
